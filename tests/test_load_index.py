from app.db.database import SessionLocal
from app.repositories.campaign_repository import CampaignRepository
from app.services.inverted_index import InvertedIndex
from app.models.campaign import Campaign
from datetime import datetime, timedelta, timezone

def test_load_index():
    db = SessionLocal()
    try:
        repository = CampaignRepository(db)
        index = InvertedIndex()
        now = datetime.now(timezone.utc)
        start_time = now - timedelta(hours=1)
        end_time = now + timedelta(hours=1)
        # Next: load campaign data from PostgreSQL
        campaign=Campaign(
            # id will be automatically generated by postgreSQL when repository.add() calls flush()
            name="Haldirams Dussherra Campaign",
            capacity=1000,
            status="ACTIVE",
            frequency_cap_per_hour=3,
            start_time=start_time,
            end_time=end_time
        )
        repository.add(campaign)
        # To add targeting values to the session
        repository.add_targeting(
            campaign,
            regions=["Mumbai"],
            devices=["Mobile"],
            subscription_tiers=["Premium"]
        )
        
        # To send the pending INSERTs to Postgres
        db.flush()
        # To add all the active campaigns to the in-memory index
        repository.load_index(index)
        
        list_of_IDs=index.find_candidates("Mumbai", "Mobile", "Premium")
        assert campaign.id in list_of_IDs, "Campaign ID is NOT part of the index"
        
        # Mismatch test
        non_matching_ids = index.find_candidates("Delhi", "Mobile", "Premium")
        assert campaign.id not in non_matching_ids, "Campaign incorrectly matched Delhi"
        
        # Retrieve Campaign objects using the indexed IDs
        campaign_objects = repository.get_candidates_by_ids(
            list_of_IDs,
            now #datetime
        )
        
        # Extract IDs from the returned Campaign objects
        returned_ids = []
        print("Campaign objects:", campaign_objects)

        for campaign_obj in campaign_objects:
            # Append the campaign object's ID to returned_ids
            returned_ids.append(campaign_obj.id)

        # Assert that our test campaign's ID is present
        assert campaign.id in returned_ids
        
        # Test a decision made before the campaign starts
        before_start = start_time - timedelta(minutes=1)

        early_candidates = repository.get_candidates_by_ids(
                list_of_IDs,
                before_start
            )

        assert campaign.id not in {c.id for c in early_candidates}

        # Test a decision made after the campaign expires
        after_end = end_time + timedelta(minutes=1)

        expired_candidates = repository.get_candidates_by_ids(
                list_of_IDs,
                after_end
            )

        assert campaign.id not in {c.id for c in expired_candidates}



    finally:
        db.rollback()
        db.close()
        
        
if __name__ == "__main__":
    test_load_index()
    print("PostgreSQL index integration test passed!")
    
